/**
 * Windows encoding bridge for OpenCode runs.
 *
 * OpenCode's shell tool on Windows runs commands through Windows PowerShell 5.1
 * by default. That host writes child output in the legacy OEM code page (for
 * example CP866 on Russian Windows), initializes `$OutputEncoding` to US-ASCII,
 * and encodes an `Invoke-RestMethod`/`Invoke-WebRequest` string body as ASCII
 * when the request type carries no charset. All three corrupt non-ASCII text:
 *
 * - Output: the shell emits OEM bytes while OpenCode decodes them as UTF-8, so
 *   Cyrillic (or CJK) text shows up as mojibake.
 * - Pipe input: `$OutputEncoding` defaults to ASCII, so text piped into `curl`,
 *   a CLI or another native process becomes a run of "?" characters.
 * - JSON request body: an `Invoke-RestMethod`/`Invoke-WebRequest` string body
 *   without a charset is sent as ASCII, so an issue title or comment the agent
 *   writes from the shell stores "?" characters.
 *
 * OpenCode 1.x does not expose a supported way to force UTF-8 on the shell it
 * spawns, so Paperclip injects a small OpenCode plugin that rewrites shell
 * commands to set UTF-8 before the original command runs. The rewrite is limited
 * to encoding:
 *
 * - The console and `$OutputEncoding` are always set to UTF-8.
 * - The default request content type is set to `application/json; charset=utf-8`
 *   only for `Invoke-RestMethod`/`Invoke-WebRequest` calls that already target
 *   JSON, so form or other non-JSON requests keep their own content type.
 *
 * The original command is wrapped in an outer scriptblock (`...settings...; & {
 * <command> }`) rather than prefixed textually, so top-level PowerShell
 * constructs such as `param(...)` and `begin`/`process`/`end` blocks stay valid
 * while still inheriting the encoding settings. A command whose first
 * non-comment token is a `using` statement is left unchanged, because PowerShell
 * requires `using` before any other statement and forbids it inside a nested
 * scriptblock, so such a command cannot be safely wrapped.
 * The hook skips a command only when the complete injected settings are already
 * present. The agent sees the rewritten command in its own history and may replay
 * a partial preamble that drops the request content type, so a weaker marker
 * check would leave a non-ASCII JSON body to be encoded as ASCII ("?").
 *
 * The plugin uses the V1 function-export shape, which OpenCode 1.x (including
 * 1.18.x) loads directly.
 */

