/**
 * OpenCode 2 plugin (Plugin.define + ctx.shell.hook) with the same UTF-8
 * guarantees as the V1 `tool.execute.before` plugin. V2 exposes the resolved
 * shell and the command through `create.before`, which is the only hook that
 * can prepend the encoding settings before PowerShell parses the command.
 */
export const PAPERCLIP_WINDOWS_UTF8_PLUGIN_V2_SOURCE = `// Generated by Paperclip. Forces UTF-8 on Windows PowerShell commands so
// agent tool input and output keep non-ASCII text.
import { Plugin } from "@opencode/plugin";

// Index of the first character of the first statement, skipping leading
// whitespace and comments, so a command that opens with a comment is still
// classified by its first real statement.
function firstStatementIndex(command) {
  const length = command.length;
  let index = 0;
  for (;;) {
    if (index >= length) break;
    const ch = command[index];
    if (ch === " " || ch === "\\t" || ch === "\\r" || ch === "\\n") { index += 1; continue; }
    if (ch === "<" && command[index + 1] === "#") {
      const end = command.indexOf("#>", index + 2);
      index = end === -1 ? length : end + 2;
      continue;
    }
    if (ch === "#") { while (index < length && command[index] !== "\\n") index += 1; continue; }
    break;
  }
  return index;
}

function paperclipWindowsUtf8Settings(command) {
  let settings =
    "$env:PAPERCLIP_WINDOWS_UTF8='1';" +
    "[Console]::OutputEncoding=[System.Text.UTF8Encoding]::new($false);" +
    "[Console]::InputEncoding=[System.Text.UTF8Encoding]::new($false);" +
    "$OutputEncoding=[System.Text.UTF8Encoding]::new($false);" +
    "$env:PYTHONIOENCODING='utf-8';$env:PYTHONUTF8='1';";
  // Windows PowerShell 5.1 encodes a string request body as ASCII when the
  // content type carries no charset, so an issue title or comment written from
  // the shell becomes a run of "?". The charset keeps the body as UTF-8.
  if (/invoke-(restmethod|webrequest)/i.test(command) && /application\\/json|convertto-json/i.test(command)) {
    settings +=
      "$PSDefaultParameterValues['Invoke-RestMethod:ContentType']='application/json; charset=utf-8';" +
      "$PSDefaultParameterValues['Invoke-WebRequest:ContentType']='application/json; charset=utf-8';";
  }
  return settings;
}

// PowerShell 5.1 encodes a string body as ASCII unless the content type names a
// charset. The default parameter covers calls that omit -ContentType, but an
// explicit application/json argument still corrupts non-ASCII text, so give
// every JSON content-type literal in a request command the UTF-8 charset.
function paperclipRewriteJsonContentType(command) {
  if (!/invoke-(restmethod|webrequest)/i.test(command)) return command;
  return command.replace(/application\\/json(?!\\s*;\\s*charset)/gi, "application/json; charset=utf-8");
}

export default Plugin.define({
  id: "paperclip.windows-utf8",
  async setup(ctx) {
    await ctx.shell.hook("create.before", (event) => {
      const shell = String(event.shell || "").toLowerCase();
      if (!shell.includes("powershell")) return;
      const command = String(event.command || "");
      if (command.length === 0) return;
      // A "using" statement must be the first statement of a PowerShell script
      // and is not allowed inside a nested scriptblock.
      if (/^using\\b/i.test(command.slice(firstStatementIndex(command)))) return;
      const rewritten = paperclipRewriteJsonContentType(command);
      const settings = paperclipWindowsUtf8Settings(rewritten);
      if (command.indexOf(settings) !== -1) {
        if (rewritten !== command) event.command = rewritten;
        return;
      }
      // Keep top-level param()/begin/process/end blocks valid by running the
      // original command inside an outer scriptblock. The trailing newline
      // keeps a final line comment from swallowing the closing brace.
      event.command = settings + "& {" + rewritten + "\\n};";
      if (event.env) {
        event.env.PYTHONIOENCODING = "utf-8";
        event.env.PYTHONUTF8 = "1";
      }
    });
  },
});
`;

