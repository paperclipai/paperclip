/**
 * Windows encoding bridge for OpenCode runs.
 *
 * OpenCode's shell tool on Windows runs commands through Windows PowerShell 5.1
 * by default. That host writes child output in the legacy OEM code page (for
 * example CP866 on Russian Windows), initializes `$OutputEncoding` to US-ASCII,
 * and encodes an `Invoke-RestMethod`/`Invoke-WebRequest` string body as ASCII
 * when the request type carries no charset. All three corrupt non-ASCII text:
 *
 * - Output: the shell emits OEM bytes while OpenCode decodes them as UTF-8, so
 *   Cyrillic (or CJK) text shows up as mojibake.
 * - Pipe input: `$OutputEncoding` defaults to ASCII, so text piped into `curl`,
 *   a CLI or another native process becomes a run of "?" characters.
 * - JSON request body: an `Invoke-RestMethod`/`Invoke-WebRequest` string body
 *   without a charset is sent as ASCII, so an issue title or comment the agent
 *   writes from the shell stores "?" characters.
 *
 * OpenCode 1.x does not expose a supported way to force UTF-8 on the shell it
 * spawns, so Paperclip injects a small OpenCode plugin that rewrites shell
 * commands to set UTF-8 before the original command runs. The rewrite is limited
 * to encoding:
 *
 * - The console and `$OutputEncoding` are always set to UTF-8.
 * - The default request content type is set to `application/json; charset=utf-8`
 *   only for `Invoke-RestMethod`/`Invoke-WebRequest` calls that already target
 *   JSON, so form or other non-JSON requests keep their own content type.
 *
 * A command whose first non-comment token is a `using` statement or a `param`
 * block is left unchanged, because PowerShell requires those before any other
 * statement. A command that only starts with comments still gets the prefix,
 * because a statement may precede a comment.
 * `$env:PAPERCLIP_WINDOWS_UTF8` marks an already-injected command, so running the
 * hook twice is harmless.
 *
 * The plugin uses the V1 function-export shape, which OpenCode 1.x (including
 * 1.18.x) loads directly.
 */

export const PAPERCLIP_WINDOWS_UTF8_PLUGIN_FILENAME = "paperclip-windows-utf8.js";

/**
 * The injected plugin source. Kept as a string so the adapter can materialize it
 * into the per-run OpenCode config directory without shipping a separate asset.
 */
export const PAPERCLIP_WINDOWS_UTF8_PLUGIN_SOURCE = `// Generated by Paperclip. Forces UTF-8 on Windows shells so agent tool output
// keeps non-ASCII text intact.
export const PaperclipWindowsUtf8 = async () => ({
  "tool.execute.before": async (input, output) => {
    if (process.platform !== "win32") return;
    const tool = String((input && input.tool) || "").toLowerCase();
    if (tool !== "bash" && tool !== "shell") return;
    const args = output && output.args;
    if (!args || typeof args.command !== "string" || args.command.length === 0) return;
    const command = args.command;
    if (command.indexOf("PAPERCLIP_WINDOWS_UTF8") !== -1) return;
    // Find the first token after leading whitespace and comments. A using
    // statement or param block must stay first, so leave such a command alone.
    const length = command.length;
    let index = 0;
    for (;;) {
      if (index >= length) break;
      const ch = command[index];
      if (ch === " " || ch === "\\t" || ch === "\\r" || ch === "\\n") { index += 1; continue; }
      if (ch === "<" && command[index + 1] === "#") {
        const end = command.indexOf("#>", index + 2);
        index = end === -1 ? length : end + 2;
        continue;
      }
      if (ch === "#") { while (index < length && command[index] !== "\\n") index += 1; continue; }
      break;
    }
    const firstToken = command.slice(index);
    if (/^using\\b/i.test(firstToken) || /^param\\s*\\(/i.test(firstToken)) return;
    let prefix =
      "$env:PAPERCLIP_WINDOWS_UTF8='1';" +
      "[Console]::OutputEncoding=[System.Text.UTF8Encoding]::new($false);" +
      "[Console]::InputEncoding=[System.Text.UTF8Encoding]::new($false);" +
      "$OutputEncoding=[System.Text.UTF8Encoding]::new($false);" +
      "$env:PYTHONIOENCODING='utf-8';$env:PYTHONUTF8='1';";
    if (/invoke-(restmethod|webrequest)/i.test(command) && /application\\/json/i.test(command)) {
      prefix +=
        "$PSDefaultParameterValues['Invoke-RestMethod:ContentType']='application/json; charset=utf-8';" +
        "$PSDefaultParameterValues['Invoke-WebRequest:ContentType']='application/json; charset=utf-8';";
    }
    args.command = prefix + command;
  },
});
`;
