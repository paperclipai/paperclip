/**
 * Provider message faults (PV1–PV3) for ACPX agents (Claude). The Codex seam
 * (provider-faults.ts) replaces the Codex executable; that does not work for
 * ACPX, whose provider package, its runtime and the sidecar are digest-verified
 * and run from private snapshots with a scrubbed environment.
 *
 * Seam, no product change:
 * 1. The harness builds a stand-in of the runner package under
 *    `<repo>/node_modules/.restart-chaos-<wave>/paperclip-runner`: symlinks to
 *    the real package, except `dist/cli/acpx-runtime-sidecar.cjs`, which is a
 *    generated stand-in sidecar. It sits under the workspace `node_modules` so
 *    that the provider package root product code derives from it is the same
 *    workspace root it derives from the real package.
 * 2. `provider-shim/acpx-sidecar-hook.mjs`, loaded into the server through
 *    NODE_OPTIONS, loads the one module that computes the local sidecar path
 *    (`runnerd-codex-transport`, from `src/live` or `dist/live`) from the stand-in package. Product
 *    code then hashes the stand-in, and the runner verifies and launches it
 *    exactly as it would the real sidecar.
 * 3. The stand-in installs `provider-shim/acpx-fault-tap.cjs` and then loads the
 *    real sidecar bundle in the same process, the way the runner's verified
 *    CommonJS loader does. The tap relays the sidecar's ACP pipe to the
 *    verified provider (still launched and admitted by product code) and the
 *    sidecar's frames to the runner, changing only the message a task's rule names.
 *
 * Rules, the log and the once-per-task markers are shared with the Codex seam.
 */
import { chmod, mkdir, readdir, realpath, rm, symlink, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { DEFAULT_PROVIDER_DELAY_MS, DEFAULT_PROVIDER_FAULT_RESTART_AFTER_MS, type ProviderFaultKind } from "./provider-faults.js";
import type { AdapterId, WaveOptions } from "./types.js";

export const ACPX_SIDECAR_HOOK = path.join(import.meta.dirname, "provider-shim", "acpx-sidecar-hook.mjs");
export const ACPX_FAULT_TAP = path.join(import.meta.dirname, "provider-shim", "acpx-fault-tap.cjs");

/** Adapters whose provider messages the harness can fault: Codex through its shim, Claude through the ACPX tap. */
export const PROVIDER_FAULT_ADAPTERS: readonly AdapterId[] = ["codex", "claude"];

export interface AcpxSidecarSeam {
  /** Merge into the server environment before it starts (kept across restarts). */
  serverEnvironment: Record<string, string>;
  standInRoot: string;
  realSidecar: string;
  /** Remove the stand-in package (after the wave). */
  remove(): Promise<void>;
}

/** The stand-in sidecar: install the tap, then run the real bundle as the runner's verified loader would. */
export function standInSidecarSource(config: { tapModule: string; realSidecar: string; controlPath: string; logPath: string; stateDirectory: string }): string {
  return `#!/usr/bin/env node
// Restart chaos stand-in ACPX sidecar (generated by tests/restart-chaos/acpx-provider-faults.ts).
"use strict";
const config = ${JSON.stringify(config)};
require(config.tapModule).installAcpxFaultTap(config);
const fs = require("node:fs");
const Module = require("node:module");
const source = fs.readFileSync(config.realSidecar, "utf8").replace(/^#![^\\r\\n]*(?:\\r?\\n|$)/, "");
const sidecar = new Module(config.realSidecar);
sidecar.filename = config.realSidecar;
sidecar.paths = [];
sidecar._compile(source, config.realSidecar);
`;
}

async function mirror(source: string, target: string, replace: Record<string, string | null>): Promise<void> {
  await mkdir(target, { recursive: true, mode: 0o755 });
  for (const entry of await readdir(source)) {
    if (entry in replace) continue;
    await symlink(path.join(source, entry), path.join(target, entry));
  }
}

/**
 * Build the stand-in runner package for `waveId` and return the server environment that loads the
 * sidecar-path module from it.
 */
export async function installAcpxSidecarSeam(input: { repositoryRoot: string; waveId: string; controlPath: string; logPath: string;
  stateDirectory: string }): Promise<AcpxSidecarSeam> {
  const realRunner = await realpath(path.join(input.repositoryRoot, "packages", "paperclip-runner"));
  const realSidecar = path.join(realRunner, "dist", "cli", "acpx-runtime-sidecar.cjs");
  for (const required of [realSidecar]) {
    if (!existsSync(required)) throw new Error(`ACPX provider faults need the built runner (${path.relative(input.repositoryRoot, required)} is missing); run node scripts/agent-preflight.mjs`);
  }
  if (!/^[A-Za-z0-9._-]+$/.test(input.waveId)) throw new Error(`Unexpected wave id ${input.waveId}`);
  const container = path.join(await realpath(path.join(input.repositoryRoot, "node_modules")), `.restart-chaos-${input.waveId}`);
  const standInRoot = path.join(container, "paperclip-runner");
  await rm(container, { recursive: true, force: true });
  // package.json and node_modules resolve to the real package; dist/cli, dist/live and src/live are
  // real directories so the stand-in sidecar can replace one file and the hook can load one module
  // (from src/ when the server runs from source, from dist/ when it runs built).
  await mirror(realRunner, standInRoot, { dist: null, src: null });
  await mirror(path.join(realRunner, "dist"), path.join(standInRoot, "dist"), { cli: null, live: null });
  await mirror(path.join(realRunner, "dist", "live"), path.join(standInRoot, "dist", "live"), {});
  if (existsSync(path.join(realRunner, "src", "live"))) {
    await mirror(path.join(realRunner, "src"), path.join(standInRoot, "src"), { live: null });
    await mirror(path.join(realRunner, "src", "live"), path.join(standInRoot, "src", "live"), {});
  }
  await mirror(path.join(realRunner, "dist", "cli"), path.join(standInRoot, "dist", "cli"), { "acpx-runtime-sidecar.cjs": null });
  const standInSidecar = path.join(standInRoot, "dist", "cli", "acpx-runtime-sidecar.cjs");
  await writeFile(standInSidecar, standInSidecarSource({ tapModule: ACPX_FAULT_TAP, realSidecar,
    controlPath: input.controlPath, logPath: input.logPath, stateDirectory: input.stateDirectory }), { mode: 0o755 });
  await chmod(standInSidecar, 0o755);
  return {
    serverEnvironment: { RESTART_CHAOS_ACPX_RUNNER_REAL: realRunner, RESTART_CHAOS_ACPX_RUNNER_SHADOW: standInRoot },
    standInRoot,
    realSidecar,
    remove: () => rm(container, { recursive: true, force: true }),
  };
}

/** NODE_OPTIONS for the server: what it already has plus the ACPX hook. */
export function withAcpxSidecarHook(nodeOptions: string | undefined): string {
  return [nodeOptions, `--import=${ACPX_SIDECAR_HOOK}`].filter(Boolean).join(" ");
}

/**
 * `--provider-fault-restart K1 [--provider-fault-restart-after-seconds n]`: each PV1/PV2 task also
 * kills -9 the control plane n seconds (default 3) after its provider fault applied. Only K1, and
 * not PV3: a duplicate has nothing in flight for a restart to cross.
 */
export function parseProviderFaultRestart(raw: string | undefined, afterRaw: string | undefined, kinds: readonly ProviderFaultKind[],
  delaysMs: readonly number[] | undefined): Pick<WaveOptions, "providerFaultRestart" | "providerFaultRestartAfterMs"> {
  if (raw === undefined) {
    if (afterRaw !== undefined) throw new Error("--provider-fault-restart-after-seconds needs --provider-fault-restart K1");
    return {};
  }
  if (raw !== "K1") throw new Error("--provider-fault-restart supports K1 (kill -9 the control plane) only");
  if (kinds.includes("PV3")) throw new Error("--provider-fault-restart combines with PV1 or PV2; a PV3 duplicate holds nothing across a restart");
  let afterMs = DEFAULT_PROVIDER_FAULT_RESTART_AFTER_MS;
  if (afterRaw !== undefined) {
    if (!/^[0-9]+(\.[0-9]+)?$/.test(afterRaw)) throw new Error("--provider-fault-restart-after-seconds must be a number of seconds");
    afterMs = Math.round(Number(afterRaw) * 1000);
    if (afterMs > 300_000) throw new Error("--provider-fault-restart-after-seconds must be at most 300");
  }
  // PV1: the restart must come while the message is still held, or it straddles nothing.
  const shortest = kinds.includes("PV1") ? Math.min(...(delaysMs?.length ? delaysMs : [DEFAULT_PROVIDER_DELAY_MS])) : null;
  if (shortest !== null && afterMs >= shortest) {
    throw new Error(`--provider-fault-restart-after-seconds (${afterMs / 1000}s) must be shorter than every PV1 delay (shortest ${shortest / 1000}s)`);
  }
  return { providerFaultRestart: "K1", providerFaultRestartAfterMs: afterMs };
}
