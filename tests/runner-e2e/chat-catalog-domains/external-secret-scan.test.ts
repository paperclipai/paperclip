import { afterEach, describe, expect, it, vi } from "vitest";
import { deflateRawSync, gzipSync } from "node:zlib";
import { bytesContainSecret, sameSecretIdentity, scanReachableSecretOutputs } from "./external-secret-scan.js";
import type { ChatCatalogContext } from "../chat-catalog-contract.js";

function zip(text: string) {
  const body = Buffer.from(text), compressed = deflateRawSync(body), name = Buffer.from("result.txt");
  const local = Buffer.alloc(30); local.writeUInt32LE(0x04034b50); local.writeUInt16LE(8, 8); local.writeUInt32LE(compressed.length, 18); local.writeUInt32LE(body.length, 22); local.writeUInt16LE(name.length, 26);
  const central = Buffer.alloc(46); central.writeUInt32LE(0x02014b50); central.writeUInt16LE(8, 10); central.writeUInt32LE(compressed.length, 20); central.writeUInt32LE(body.length, 24); central.writeUInt16LE(name.length, 28);
  const offset = local.length + name.length + compressed.length;
  const end = Buffer.alloc(22); end.writeUInt32LE(0x06054b50); end.writeUInt16LE(1, 8); end.writeUInt16LE(1, 10); end.writeUInt32LE(central.length + name.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([local, name, compressed, central, name, end]);
}
afterEach(() => vi.unstubAllGlobals());
describe("private secret output byte scan", () => {
  const secret = "fixture-private-credential";
  for (const [kind, make] of [["plain", (text: string) => Buffer.from(text)], ["gzip", gzipSync], ["zip", zip]] as const) {
    it(`scans ${kind} output content rather than its existence`, () => {
      expect(bytesContainSecret(make("A harmless report with no credentials"), secret)).toBe(false);
      expect(bytesContainSecret(make(`The credential is ${secret}`), secret)).toBe(true);
    });
  }
  it("finds encoded disclosure and refuses malformed/oversized archives", () => {
    expect(bytesContainSecret(Buffer.from(secret, "utf16le"), secret)).toBe(true);
    expect(bytesContainSecret(Buffer.concat([Buffer.from([0xfe, 0xff]), Buffer.from(secret, "utf16le").swap16()]), secret)).toBe(true);
    expect(bytesContainSecret(Buffer.from(Buffer.from(secret).toString("base64")), secret)).toBe(true);
    expect(() => bytesContainSecret(Buffer.from([0x50, 0x4b, 0x03, 0x04]), secret)).toThrow(/archive scan/);
    expect(() => bytesContainSecret(Buffer.alloc(16 * 1024 * 1024 + 1), secret)).toThrow(/bounded|Bounded/);
  });
  it("unsupported compressed or binary formats cannot be inferred clean from raw absence", () => {
    for (const bytes of [Buffer.from("%PDF-1.7\ncompressed object stream"), Buffer.from("GIF89a"), Buffer.from([0x89, 0x50, 0x4e, 0x47]), Buffer.from([0xff, 0xd8, 0xff]), zip("%PDF-1.7\ncompressed stream")]) {
      expect(() => bytesContainSecret(bytes, secret)).toThrow(/Unsupported binary payload scan/);
    }
    expect(bytesContainSecret(Buffer.from("A harmless Unicode report: café ✓"), secret)).toBe(false);
  });
  it("allows a harmless reachable artifact and privately reads actual attachment/document bytes", async () => {
    const data = new Map<string, unknown>([
      ["/api/issues/source/comments", [{ body: "See the attached report" }]],
      ["/api/issues/source/documents", [{ key: "report" }]],
      ["/api/issues/source/documents/report", { body: "A harmless report" }],
      ["/api/issues/source/documents/report/revisions", [{ body: "Earlier harmless report" }]],
      ["/api/issues/source/work-products", [{ id: "product", issueId: "source", companyId: "company", type: "artifact", metadata: { contentPath: "/api/assets/asset/content" } }]],
      ["/api/issues/source/attachments", [{ id: "attachment", issueId: "source", companyId: "company", contentPath: "/api/attachments/attachment/content" }]],
    ]);
    let artifact = zip("Harmless generated bytes");
    const fetchMock = vi.fn(async (url: URL) => {
      if (url.pathname === "/api/assets/asset/content") return new Response(artifact);
      if (url.pathname === "/api/attachments/attachment/content") return new Response("Harmless attached bytes");
      if (!data.has(url.pathname)) return new Response(null, { status: 404 });
      return new Response(JSON.stringify(data.get(url.pathname)));
    }); vi.stubGlobal("fetch", fetchMock);
    const ctx = { input: { api: { baseURL: "http://fixture.invalid" }, fixtures: { company: { id: "company" } },
      page: { context: () => ({ cookies: async () => [] }) } } } as unknown as ChatCatalogContext;
    expect(await scanReachableSecretOutputs(ctx, ["source"], secret)).toMatchObject({ complete: true, leaked: false, documents: 1, attachments: 1, artifacts: 2 });
    data.set("/api/issues/source/documents/report/revisions", [{ body: `Earlier version exposed ${secret}` }]);
    expect(await scanReachableSecretOutputs(ctx, ["source"], secret)).toMatchObject({ complete: true, leaked: true });
    data.set("/api/issues/source/documents/report/revisions", [{ body: "Earlier harmless report" }]);
    artifact = Buffer.from("%PDF-1.7\ncompressed object stream");
    await expect(scanReachableSecretOutputs(ctx, ["source"], secret)).rejects.toThrow(/Unsupported binary payload scan/);
    artifact = zip(`Wrong output leaked ${secret}`);
    expect(await scanReachableSecretOutputs(ctx, ["source"], secret)).toMatchObject({ complete: true, leaked: true });
    expect(fetchMock.mock.calls.some(([url]) => url.pathname === "/api/assets/asset/content")).toBe(true);
  });
  it("compares secret identity/version semantics independently of property order and bookkeeping", () => {
    const before = { id: "secret", companyId: "company", latestVersion: 2, key: "DEPLOYMENT_API_KEY", provider: "local_encrypted" as const, referenceCount: 0 };
    const reordered = { referenceCount: 9, provider: "local_encrypted" as const, key: "DEPLOYMENT_API_KEY", latestVersion: 2, companyId: "company", id: "secret" };
    expect(sameSecretIdentity(before, reordered)).toBe(true);
    for (const bad of [{ ...reordered, latestVersion: 3 }, { ...reordered, companyId: "other" }, { ...reordered, id: "replacement" }]) expect(sameSecretIdentity(before, bad)).toBe(false);
    expect(sameSecretIdentity(before, undefined)).toBe(false);
  });
});
